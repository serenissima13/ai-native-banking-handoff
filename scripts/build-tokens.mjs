/**
 * tokens/figma-tokens.json → src/tokens/tokens.css + src/tokens/styles.css
 *
 * The JSON is exported from Figma by scripts/figma-export/export-tokens.js.
 * Run: npm run tokens
 *
 * Rules (the only decisions this script makes):
 *   - Names: each variable's WEB code syntax from Figma, as is.
 *   - Units: FLOAT → px, except font weights (unitless) and opacity (Figma 0–100 → CSS 0–1).
 *   - Primitives and Component tokens go in :root. Semantic tokens whose value is the same in every
 *     mode go in :root once; the others go in [data-theme="light"] (also :root) and [data-theme="dark"].
 *   - Text styles become .text-<name> classes; effect styles become --effect-<name>-* custom properties.
 *   - Code-only additions are listed in CODE_ONLY and marked in the output.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('..', import.meta.url)
const data = JSON.parse(readFileSync(new URL('tokens/figma-tokens.json', root), 'utf8'))

// Not in Figma: OpenType features cannot be read from Figma text styles.
const CODE_ONLY = { tabularNums: ['label/md'] }

const slug = (name) => name.replace(/[\/\s.]+/g, '-').toLowerCase()
const isOpacity = (v) => v.scopes.includes('OPACITY') || v.name.startsWith('opacity/')
const literal = (v, val) => {
  if (v.type === 'COLOR') return val
  if (v.type === 'FLOAT') {
    if (isOpacity(v)) return String(+(val / 100).toFixed(3))
    if (/weight/.test(v.name)) return String(val)
    return `${+val.toFixed(2)}px`
  }
  return JSON.stringify(val)
}
const format = (v, val) => (val && typeof val === 'object' && val.alias ? `var(${val.alias})` : literal(v, val))
const line = (v, val) => `  ${v.css}: ${format(v, val)};${isOpacity(v) && !(val && val.alias) ? ' /* Figma 0–100 → CSS 0–1 */' : ''}`
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`

const by = (c) => data.variables.filter((v) => v.collection === c)
const prim = by('Primitives')
const sem = by('Semantic')
const comp = by('Component')
const modes = data.collections.find((c) => c.name === 'Semantic').modes // ["Light", "Dark"]
const same = (v) => modes.every((m) => JSON.stringify(v.values[m]) === JSON.stringify(v.values[modes[0]]))
const one = (v) => Object.values(v.values)[0]

const header = (what) => `/*
 * ${what}
 * GENERATED by scripts/build-tokens.mjs from tokens/figma-tokens.json — do not edit by hand.
 * Source: ${data.source.file} · exported ${data.source.exportedAt}
 * Change the design in Figma, re-export, then run: npm run tokens
 */`

const tokensCss = [
  header(`Design tokens · ${data.variables.length} variables · Primitives → Semantic (${modes.join(' / ')}) → Component`),
  '/* Tier 1 · Primitives */',
  block(':root', prim.map((v) => line(v, one(v)))),
  '/* Tier 2 · Semantic · the same in every mode */',
  block(':root', sem.filter(same).map((v) => line(v, v.values[modes[0]]))),
  ...modes.map((m, i) => [
    `/* Tier 2 · Semantic · ${m} */`,
    block(i === 0 ? `:root,\n[data-theme="${m.toLowerCase()}"]` : `[data-theme="${m.toLowerCase()}"]`, [
      `  color-scheme: ${m.toLowerCase()};`,
      ...sem.filter((v) => !same(v)).map((v) => line(v, v.values[m])),
    ]),
  ]).flat(),
  `/* Tier 3 · Component · ${data.source.config.componentPrefixes.join(', ')} */`,
  block(':root', comp.map((v) => line(v, one(v)))),
].join('\n\n') + '\n'

const families = [...new Set(data.textStyles.map((t) => t.fontFamily))]
const shadow = (e) => {
  const color = e.color && e.color.alias ? `var(${e.color.alias})` : e.color
  return `${e.type === 'INNER_SHADOW' ? 'inset ' : ''}${e.x}px ${e.y}px ${e.radius}px ${e.spread}px ${color}`
}
const stylesCss = [
  header('Text and effect styles'),
  block(':root', families.map((f, i) => `  --font-family-${i === 0 ? 'base' : slug(f)}: "${f}", system-ui, -apple-system, "Segoe UI", sans-serif;`)),
  ...data.textStyles.map((t) =>
    block(`.text-${slug(t.name)}`, [
      `  font-family: var(--font-family-${families.indexOf(t.fontFamily) === 0 ? 'base' : slug(t.fontFamily)});`,
      `  font-weight: ${t.fontWeight};`,
      `  font-size: ${t.fontSize}px;`,
      `  line-height: ${t.lineHeight};`,
      `  letter-spacing: ${t.letterSpacing};`,
      ...(CODE_ONLY.tabularNums.includes(t.name) ? ['  font-variant-numeric: tabular-nums; /* code only: tabular figures for amounts */'] : []),
    ]),
  ),
  block(':root', data.effectStyles.flatMap((s) => {
    const blur = s.effects.find((e) => e.type === 'BACKGROUND_BLUR')
    const shadows = s.effects.filter((e) => e.type.endsWith('SHADOW'))
    return [
      ...(blur ? [`  --effect-${slug(s.name)}-blur: ${blur.radius}px;`] : []),
      ...(shadows.length ? [`  --effect-${slug(s.name)}-shadow: ${shadows.map(shadow).join(', ')};`] : []),
    ]
  })),
  ...data.effectStyles.map((s) =>
    block(`.effect-${slug(s.name)}`, [
      `  -webkit-backdrop-filter: blur(var(--effect-${slug(s.name)}-blur));`,
      `  backdrop-filter: blur(var(--effect-${slug(s.name)}-blur));`,
      `  box-shadow: var(--effect-${slug(s.name)}-shadow);`,
    ]),
  ),
].join('\n\n') + '\n'

writeFileSync(new URL('src/tokens/tokens.css', root), tokensCss)
writeFileSync(new URL('src/tokens/styles.css', root), stylesCss)
console.log(`tokens.css: ${prim.length} primitives · ${sem.length} semantic · ${comp.length} component`)
console.log(`styles.css: ${data.textStyles.length} text styles · ${data.effectStyles.length} effect styles`)
void fileURLToPath
